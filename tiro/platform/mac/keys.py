for _mac, _vk in MAC_TO_VK.items():
    VK_TO_MAC.setdefault(_vk, _mac)

# Modifier keys arrive as "flags changed" events; these device-dependent flag bits say whether that
# particular key (left or right) is now down.
MODIFIER_BITS: dict[int, int] = {
    0x3B: 0x00000001,  # left control
    0x38: 0x00000002,  # left shift
    0x3C: 0x00000004,  # right shift
    0x37: 0x00000008,  # left command
    0x36: 0x00000010,  # right command
    0x3A: 0x00000020,  # left option
    0x3D: 0x00000040,  # right option
    0x3E: 0x00002000,  # right control
    0x3F: 0x00800000,  # fn (kCGEventFlagMaskSecondaryFn)
    0x39: 0x00010000,  # caps lock (kCGEventFlagMaskAlphaShift)
}

FLAG_SHIFT = 0x00020000
FLAG_CONTROL = 0x00040000
FLAG_OPTION = 0x00080000
FLAG_COMMAND = 0x00100000
